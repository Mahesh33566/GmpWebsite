export function calculateIPOStats(ipo: IPO) {
  const gmpRate = Number(((ipo.gmp / ipo.issuePrice) * 100).toFixed(2));
  const estListingPrice = ipo.issuePrice + ipo.gmp;
  const lotInvestment = ipo.issuePrice * ipo.lotSize;
  const estProfitPerLot = ipo.gmp * ipo.lotSize;
  const isRecommended = gmpRate >= 30;

  return {
    gmpRate,
    estListingPrice,
    lotInvestment,
    estProfitPerLot,
    isRecommended,
    recommendationLabel: isRecommended ? 'Must Purchase' : 'Not Recommended',
    badgeVariant: isRecommended ? 'success' : 'warning',
  };
}
